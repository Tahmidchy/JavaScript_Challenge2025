// Solution: 
/*
Callback Hell (কলব্যাক হেল) বা Pyramid of Doom হলো জাভাস্ক্রিপ্টে অ্যাসিঙ্ক্রোনাস (asynchronous) কোড লেখার সময় যখন একের পর এক অনেকগুলো কলব্যাক ফাংশন একে অপরের ভেতরে নেস্টেড (nested) বা ঢুকে থাকে, ফলে কোডটি দেখতে পিরামিডের মতো হয়ে যায় এবং পড়া বা রক্ষণাবেক্ষণ করা কঠিন হয়ে পড়ে [১, ২, ১০]। এটি সাধারণত তখন হয় যখন একটি কাজের ওপর নির্ভর করে অন্য কাজ (dependent asynchronous tasks) পর্যায়ক্রমে করতে হয়, যেমন- ডাটাবেস থেকে তথ্য এনে API কলে ব্যবহার করা [১, ৩]। এর মূল সমাধান হলো Promise (প্রমিজ) ব্যবহার করা অথবা আধুনিক Async/Await (অ্যাসিঙ্ক/অ্যাওয়েট) ব্যবহার করে কোডটি ফ্ল্যাট বা সোজা করে লেখা 
*/

/*
কলব্যাক হেল বা পিরামিড অফ ডুম সম্পর্কে বিস্তারিত:
সংজ্ঞা: যখন একটি ফাংশনের ভেতরে আরেকটি, তার ভেতরে আরেকটি—এভাবে কলব্যাক চলতে থাকে (Nested Callbacks), তখন কোডের গঠনটি ডানদিকে হেলে গিয়ে পিরামিডের মতো আকার নেয়।

*/

/*
সমাধান (How to Fix):

Promises ব্যবহার (Promise Chaining): কলব্যাকের বদলে .then() ব্যবহার করে কোডকে নিচের দিকে সোজাভাবে (Linear structure) নিয়ে আসা [৩, ৫]।

Async/Await ব্যবহার: এটি সবথেকে আধুনিক এবং পরিষ্কার পদ্ধতি। এটি অ্যাসিঙ্ক্রোনাস কোডকে সিনক্রোনাস বা সোজা কোডের মতো লিখতে সাহায্য করে, যা পড়তে সহজ [৫]।

ফাংশন মডুলারাইজেশন (Modularization): বড় কলব্যাক ফাংশনগুলোকে আলাদা আলাদা ছোট ফাংশনে ভেঙে নেওয়া [৩]।

*/